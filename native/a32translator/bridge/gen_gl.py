"""GLES/EGL thunks, generated from the NDK's headers (called by gen_stubs.py):

  guest/gen/gl_stubs.S  one hypercall stub per function (HC_GL + index), exported by the runtime
  host/gen/gl.c         the host side: arguments read per type, the host function called through a pointer that
                        gl_resolve() looks up (libGLESv3/libEGL, else eglGetProcAddress)

Functions whose arguments can't be passed through as they are (pointer arrays, host pointers as results, callbacks)
are written by hand in host/gl.c (SPECIAL), or left out: their stub logs the name and returns 0.
"""
import re
from pathlib import Path

HEADERS = ["GLES3/gl32.h", "GLES2/gl2ext.h", "EGL/egl.h", "EGL/eglext.h"]
HC_GL = 0x1000
# host pointers the guest sees as handles (handles.c ptr2h)
HANDLES = {"EGLDisplay", "EGLSurface", "EGLContext", "EGLConfig", "EGLImageKHR", "EGLImage", "EGLSyncKHR", "EGLSync",
           "EGLClientBuffer", "EGLNativeWindowType", "EGLNativePixmapType", "EGLNativeDisplayType", "EGLStreamKHR",
           "GLeglImageOES", "EGLDeviceEXT", "EGLOutputLayerEXT", "EGLOutputPortEXT", "GLeglClientBufferEXT",
           "EGLLabelKHR", "EGLObjectKHR", "EGLSyncNV"}
SYNC = {"GLsync"}  # freed with glDeleteSync: their own table (gl.c)
FLOAT = {"GLfloat", "GLclampf"}
INT64 = {"GLint64", "GLuint64", "GLint64EXT", "GLuint64EXT", "EGLTimeKHR", "EGLTime", "EGLuint64KHR",
         "EGLnsecsANDROID", "EGLuint64NV", "EGLTimeNV"}
INTPTR = {"GLintptr", "GLsizeiptr", "GLintptrARB", "EGLAttrib", "EGLAttribKHR", "EGLsizeiANDROID"}
CALLBACK = re.compile(r"PROC|Func")
# hand-written in host/gl.c as gl_<name>(a32_cpu *c, argreader *R, void *fn)
SPECIAL = {
    "glShaderSource", "glGetString", "glGetStringi", "eglQueryString", "glMapBufferRange", "glMapBufferRangeEXT",
    "glMapBufferOES", "glUnmapBuffer", "glUnmapBufferOES", "glFlushMappedBufferRange",
    "glFlushMappedBufferRangeEXT", "eglChooseConfig", "eglGetConfigs", "glTransformFeedbackVaryings",
    "glGetUniformIndices", "glDeleteSync", "glDebugMessageCallback", "glDebugMessageCallbackKHR",
}
GUEST_IMPL = {"eglGetProcAddress"}  # implemented inside the runtime (guest/gl.c)


def parse(include: Path):
    funcs = {}
    for h in HEADERS:
        text = (include / h).read_text()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        for m in re.finditer(r"(?:GL_APICALL|EGLAPI)\s+(.+?)\s*(?:GL_APIENTRY|EGLAPIENTRY)\s+(\w+)\s*\(([^;]*?)\)\s*;",
                             text, re.S):
            ret, name, params = " ".join(m.group(1).split()), m.group(2), " ".join(m.group(3).split())
            if name in funcs:
                continue
            ps = [] if params in ("", "void") else [p.strip() for p in params.split(",")]
            types = []
            for p in ps:
                # drop the parameter name (the last identifier, unless the whole thing is a type)
                t = re.sub(r"\b(\w+)\s*(\[\s*\w*\s*\])?$", "", p).strip() if not p.endswith("*") else p
                if not t or t in ("const",):
                    t = p
                if re.search(r"\[\s*\w*\s*\]$", p):
                    t += " *"
                types.append(" ".join(t.split()))
            funcs[name] = (ret, types)
    return funcs


def kind(t: str) -> str:
    t = t.replace("const", "").strip()
    stars = t.count("*")
    base = t.replace("*", "").strip()
    if stars >= 2:
        return "?"
    if stars == 1:
        if base in HANDLES or base in SYNC or base in INTPTR:
            return "?"  # arrays of host-sized values: by hand
        return "P"
    if CALLBACK.search(base):
        return "?"
    if base == "void":
        return "v"
    if base in HANDLES:
        return "H"
    if base in SYNC:
        return "Y"
    if base in FLOAT:
        return "f"
    if base in INT64:
        return "J"
    if base in INTPTR:
        return "Z"
    if base.startswith("__egl"):  # eglGetProcAddress's result type
        return "?"
    return "I"


def generate(ndk: str, gdir: Path, hdir: Path) -> list[str]:
    include = Path(ndk) / "toolchains/llvm/prebuilt/linux-x86_64/sysroot/usr/include"
    funcs = parse(include)
    names = sorted(n for n in funcs if n not in GUEST_IMPL)
    out = ["/* generated by bridge/gen_gl.py from the NDK's GLES/EGL headers: do not edit */", "",
           "#define GL_GLEXT_PROTOTYPES 1", "#define EGL_EGLEXT_PROTOTYPES 1", "#include <EGL/egl.h>",
           "#include <EGL/eglext.h>", "#include <GLES3/gl32.h>", "#include <GLES2/gl2ext.h>",
           '#include "../gl_internal.h"', ""] + [f"void gl_{n}(a32_cpu *c, argreader *R, void *fn);" for n in sorted(SPECIAL)] + ["",
           f"const int gl_count = {len(names)};", "const char *const gl_names[] = {"]
    out += [f'    "{n}",' for n in names] + ["};", "",
                                              "int gl_dispatch_generated(a32_cpu *c, int index, argreader *R, void *fn)",
                                              "{", "    switch (index) {"]
    skipped = []
    for i, n in enumerate(names):
        ret, types = funcs[n]
        if n in SPECIAL:
            out += [f"    case {i}: gl_{n}(c, R, fn); return 1;"]
            continue
        ks = [kind(t) for t in types]
        rk = kind(ret)
        if "?" in ks or rk == "?" or "v" in ks or (rk == "P" and not re.search(r"char|GLubyte", ret)):
            skipped.append(n)
            continue
        decl, args = [], []
        for k, (kd, t) in enumerate(zip(ks, types)):
            v = f"a{k}"
            ct = t
            if kd == "I":
                decl.append(f"{ct} {v} = ({ct})rd32(R);")
            elif kd == "f":
                decl.append(f"{ct} {v} = rdf(R);")
            elif kd == "J":
                decl.append(f"{ct} {v} = ({ct})rd64(R);")
            elif kd == "Z":
                decl.append(f"{ct} {v} = ({ct})(int32_t)rd32(R);")
            elif kd == "H":
                decl.append(f"{ct} {v} = ({ct})h2ptr(rd32(R));")
            elif kd == "Y":
                decl.append(f"{ct} {v} = ({ct})h2sync(rd32(R));")
            elif kd == "P":
                decl.append(f"{ct} {v} = ({ct})g2p(rd32(R));")
            args.append(v)
        call = f"((__typeof__(&{n}))fn)({', '.join(args)})"
        body = ["        " + d for d in decl]
        if rk == "v":
            body.append(f"        {call};")
        elif rk == "I":
            body.append(f"        ret32(c, (uint32_t){call});")
        elif rk == "f":
            body.append(f"        retf(c, {call});")
        elif rk == "J":
            body.append(f"        ret64(c, (uint64_t){call});")
        elif rk == "Z":
            body.append(f"        ret32(c, (uint32_t)(intptr_t){call});")
        elif rk == "H":
            body.append(f"        ret32(c, ptr2h((void *){call}));")
        elif rk == "Y":
            body.append(f"        ret32(c, sync2h((void *){call}));")
        elif rk == "P":
            body.append(f"        ret32(c, gl_guest_string((const char *){call}));")
        out += [f"    case {i}: {{ /* {n} */"] + body + ["        return 1;", "    }"]
    out += ["    }", "    return 0;", "}", ""]
    (hdir / "gl.c").write_text("\n".join(out))

    st = ["/* generated by bridge/gen_gl.py: do not edit */", "    .syntax unified", "    .arm", "    .text",
          "    .p2align 2"]
    for i, n in enumerate(names):
        hc = 0x0A320000 | (HC_GL + i)
        st += [f"    .global {n}", f"    .type {n}, %function", f"{n}:", "    push {r7, lr}",
               f"    movw r7, #{hc & 0xffff:#x}", f"    movt r7, #{hc >> 16:#x}", "    svc 0", "    pop {r7, pc}"]
    st += ["    .section .note.GNU-stack, \"\", %progbits", ""]
    (gdir / "gl_stubs.S").write_text("\n".join(st))
    (gdir / "gl_skipped.txt").write_text("\n".join(skipped) + "\n")
    return names + sorted(GUEST_IMPL), len(skipped)
